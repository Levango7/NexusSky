-- V26__airspace_reservations.sql: 4D 空域预约持久化（B5 的内存态预约表落库）
--
-- 口径：时间用 epoch 毫秒（绝对时间）——相对秒在落库后重启会语义断裂
-- （相对窗口没有绝对锚点），故 B5 的相对秒口径在本迁移同期升级为绝对时间。
-- lat/lon/alt/radius 与 ConflictAvoidanceService.Reservation4D 一致（double）。

CREATE TABLE IF NOT EXISTS airspace_reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_sysid INTEGER NOT NULL,
    lat DOUBLE PRECISION NOT NULL,
    lon DOUBLE PRECISION NOT NULL,
    alt DOUBLE PRECISION NOT NULL,
    start_ms DOUBLE PRECISION NOT NULL,
    end_ms DOUBLE PRECISION NOT NULL,
    radius_m DOUBLE PRECISION NOT NULL,
    created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_airspace_reservations_owner ON airspace_reservations (owner_sysid);
CREATE INDEX IF NOT EXISTS idx_airspace_reservations_end ON airspace_reservations (end_ms);
