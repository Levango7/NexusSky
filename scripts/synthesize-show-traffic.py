#!/usr/bin/env python3
"""低空经济场景合成轨迹造数器（表演/物流/农业/应急共用同一张 flight_log）。

用途：按「机数 × 频率 × 时长」生成 flight_log 轨迹，实测写入吞吐与表体积，
为分库分表/分区与备份恢复容量规划提供真实数字（不是纸面估算）。

默认只往**独立演练库**写（--create-db 时用超级用户建库），不碰生产库。

示例（1200 架表演，10Hz，900s）：
  python scripts/synthesize-show-traffic.py --drones 1200 --hz 10 --duration 900 \
      --task-id show-1200 --create-db --db aerofleet_show_drill

示例（只算不写）：
  python scripts/synthesize-show-traffic.py --drones 1200 --hz 10 --duration 900 --dry-run
"""
import argparse
import math
import subprocess
import sys
import time

CONTAINER = "opsmesh-p0a3-pg"
ADMIN_USER = "opsmesh"
ADMIN_PASS = "opsmesh123"
APP_USER = "aerofleet"


def psql(db, sql, user=APP_USER, admin=False):
    if admin:
        cmd = ["docker", "exec", CONTAINER, "env", "PGPASSWORD=" + ADMIN_PASS,
               "psql", "-h", "127.0.0.1", "-U", ADMIN_USER, "-d", "postgres", "-t", "-c", sql]
    else:
        cmd = ["docker", "exec", CONTAINER, "psql", "-U", user, "-d", db, "-t", "-c", sql]
    return subprocess.run(cmd, capture_output=True, text=True)


def copy_rows(db, rows_iter, columns):
    """用 COPY FROM STDIN 流式灌入，返回 (秒, 行数)。"""
    cmd = ["docker", "exec", "-i", CONTAINER, "psql", "-U", APP_USER, "-d", db,
           "-c", "COPY flight_log (%s) FROM STDIN" % ",".join(columns)]
    t = time.monotonic()
    p = subprocess.Popen(cmd, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                         stderr=subprocess.PIPE, text=True)
    n = 0
    for line in rows_iter:
        p.stdin.write(line)
        n += 1
    p.stdin.close()
    out, err = p.communicate()
    dur = time.monotonic() - t
    if p.returncode != 0:
        raise RuntimeError("COPY failed: %s" % err.strip()[:300])
    return round(dur, 2), n


def gen_rows(drones, hz, duration, task_id, group_size, tenant_id, base_lat, base_lon):
    cols = ["timestamp", "type", "sysid", "lat", "lon", "relative_alt", "groundspeed",
            "battery", "mode", "armed", "online", "severity", "text",
            "tenant_id", "task_id", "formation_id", "seq"]
    start = time.time()
    for d in range(1, drones + 1):
        gid = "g-%02d" % ((d - 1) // group_size)
        for i in range(int(hz * duration)):
            ts = start + i / hz
            # 简单圆周轨迹，保证 lat/lon/alt 有真实变化
            ang = 2 * math.pi * (i / (hz * duration))
            lat = base_lat + 0.001 * math.cos(ang) + d * 1e-6
            lon = base_lon + 0.001 * math.sin(ang) + d * 1e-6
            alt = 50 + 20 * math.sin(ang)
            yield "\t".join([
                time.strftime("%Y-%m-%d %H:%M:%S", time.gmtime(ts)) + "+00",
                "telemetry", str(d), "%.7f" % lat, "%.7f" % lon, "%.2f" % alt,
                "%.2f" % (5 + 3 * math.sin(ang)), str(100 - (i % 40)),
                "GUIDED", "t", "t", "0", "", str(tenant_id), task_id, gid, str(i),
            ]) + "\n"
    return cols


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--drones", type=int, default=200)
    ap.add_argument("--hz", type=float, default=10)
    ap.add_argument("--duration", type=float, default=900)
    ap.add_argument("--task-id", default="show-drill")
    ap.add_argument("--group-size", type=int, default=50)
    ap.add_argument("--tenant-id", type=int, default=1)
    ap.add_argument("--db", default="aerofleet_show_drill")
    ap.add_argument("--create-db", action="store_true")
    ap.add_argument("--append", action="store_true",
                    help="不清空目标表；默认先 TRUNCATE（seq 从 0 重来会撞唯一索引）")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--base-lat", type=float, default=30.0)
    ap.add_argument("--base-lon", type=float, default=120.0)
    a = ap.parse_args()

    expected = a.drones * int(a.hz * a.duration)
    print("expected rows = %d (%d drones x %.0fHz x %.0fs)" % (expected, a.drones, a.hz, a.duration))
    if a.dry_run:
        return 0

    if a.create_db:
        psql(None, "drop database if exists %s" % a.db, admin=True)
        r = psql(None, "create database %s owner %s" % (a.db, APP_USER), admin=True)
        if r.returncode != 0:
            print("create db failed:", r.stderr.strip()[:200]); return 1
        # 建表：与生产 flight_log 同构（含 V42 新列）
        ddl = """CREATE TABLE flight_log (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            timestamp TIMESTAMPTZ, type VARCHAR(50), sysid INTEGER,
            lat DOUBLE PRECISION, lon DOUBLE PRECISION, relative_alt DOUBLE PRECISION,
            groundspeed DOUBLE PRECISION, battery INTEGER, voltage INTEGER,
            mode VARCHAR(50), armed BOOLEAN, online BOOLEAN, severity INTEGER,
            text VARCHAR(2000), tenant_id INTEGER,
            task_id VARCHAR(64), formation_id VARCHAR(64), seq BIGINT);
            CREATE INDEX idx_flight_log_tenant_task_time ON flight_log (tenant_id, task_id, timestamp);
            CREATE UNIQUE INDEX uq_flight_log_tenant_sysid_seq ON flight_log (tenant_id, sysid, seq);"""
        r = psql(a.db, ddl)
        if r.returncode != 0:
            print("ddl failed:", r.stderr.strip()[:300]); return 1

    cols = ["timestamp", "type", "sysid", "lat", "lon", "relative_alt", "groundspeed",
            "battery", "mode", "armed", "online", "severity", "text",
            "tenant_id", "task_id", "formation_id", "seq"]
    if not a.append:
        r = psql(a.db, "TRUNCATE flight_log RESTART IDENTITY;")
        if r.returncode != 0:
            print("truncate failed:", r.stderr.strip()[:200]); return 1
    rows = gen_rows(a.drones, a.hz, a.duration, a.task_id, a.group_size,
                    a.tenant_id, a.base_lat, a.base_lon)
    dur, n = copy_rows(a.db, rows, cols)
    print("inserted rows = %d in %.2fs (%.0f rows/s)" % (n, dur, n / dur if dur else 0))

    r = psql(a.db, "select pg_size_pretty(pg_total_relation_size('flight_log'));")
    print("table size (with indexes) =", r.stdout.strip())
    r = psql(a.db, "select count(distinct formation_id) from flight_log;")
    print("groups =", r.stdout.strip())
    return 0


if __name__ == "__main__":
    sys.exit(main())
