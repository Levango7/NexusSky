-- flight_log 按月分区蓝图（**维护窗口执行，不放进 Flyway 自动迁移**）
--
-- 为什么不是 V43 自动迁移：
--   1. 把现有表换成分区表 = 新建表 + 全量拷贝 + 改名 + 重建外键/索引/权限，
--      在运行期执行会锁表并让在线写入落到旧表；必须停机或在只读窗口做。
--   2. 仓库有 check-destructive-migration.py：DROP/RENAME 类迁移必须在回滚手册登记。
--   3. 2026-11-23 的 10.8M 行演练里，全量 INSERT ... SELECT 用了 26.7s（服务端同机），
--      真实生产库要按 2–3 倍估。
--
-- 本文件只提供可直接执行的结构 + 步骤注释；执行前请先备份，并在演练库跑一遍。
--
-- 实测依据（kind/本机 PG 15.19，10.8M 行 = 1200 架 × 10Hz × 900s）：
--   * 非分区表（heap 1623 MB + 索引 627 MB = 2250 MB）：
--       DELETE 1 个月数据 11.9s（之后还要 autovacuum 才能回收空间）
--   * 分区表（单月分区 1947 MB + 主键 324 MB）：
--       DROP TABLE 单月分区 0.176s，分区裁剪生效（EXPLAIN 只扫命中分区）
--   * PG 15.19 实测支持分区表上的 GENERATED BY DEFAULT AS IDENTITY（含 attach partition）。
--
-- 维护窗口步骤（建议逐条核对，不要一次粘贴）：
--   1) pg_dump -Fc 备份；确认 dump 可 pg_restore --list。
--   2) 停写入（或切只读）；记录当前最大 id。
--   3) 按本文件建 flight_log_p 及历史月份分区（起始月份按最早 timestamp 定）。
--   4) INSERT INTO flight_log_p SELECT ... FROM flight_log;（顺序与列显式列出）
--   5) 校验 count(*) / min(timestamp) / max(timestamp) / sum(hashtext(...)) 一致。
--   6) BEGIN; ALTER TABLE flight_log RENAME TO flight_log_legacy;
--            ALTER TABLE flight_log_p RENAME TO flight_log;
--      COMMIT; 然后重建序列归属与权限（见文件末尾）。
--   7) 观察一个写入周期；确认无报错后再 DROP TABLE flight_log_legacy。
--
-- 日常运维：
--   * 每月提前建下月分区（可用 pg_cron 调 ensure_flight_log_partition）。
--   * 保留期到点用 DROP TABLE，不要 DELETE（11.9s + 膨胀 vs 0.176s）。
--   * 归档：先 pg_dump 单分区，再 DROP。

-- ===== 1. 父表 =====
CREATE SEQUENCE IF NOT EXISTS flight_log_id_seq;

CREATE TABLE IF NOT EXISTS flight_log_p (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    timestamp     TIMESTAMPTZ,
    type          VARCHAR(50),
    sysid         INTEGER,
    lat           DOUBLE PRECISION,
    lon           DOUBLE PRECISION,
    relative_alt  DOUBLE PRECISION,
    groundspeed   DOUBLE PRECISION,
    battery       INTEGER,
    voltage       INTEGER,
    mode          VARCHAR(50),
    armed         BOOLEAN,
    online        BOOLEAN,
    severity      INTEGER,
    text          VARCHAR(2000),
    tenant_id     INTEGER,
    task_id       VARCHAR(64),
    formation_id  VARCHAR(64),
    seq           BIGINT,
    -- 分区表的主键必须包含分区键 timestamp
    PRIMARY KEY (id, timestamp)
) PARTITION BY RANGE (timestamp);

-- ===== 2. 分区自动创建（按月） =====
CREATE OR REPLACE FUNCTION ensure_flight_log_partition(month_start DATE)
RETURNS TEXT LANGUAGE plpgsql AS $$
DECLARE
    part_name TEXT := 'flight_log_' || to_char(month_start, 'YYYY_MM');
    next_month DATE := (month_start + INTERVAL '1 month')::date;
BEGIN
    IF to_regclass(part_name) IS NULL THEN
        EXECUTE format(
            'CREATE TABLE %I PARTITION OF flight_log_p FOR VALUES FROM (%L) TO (%L)',
            part_name, month_start, next_month);
    END IF;
    RETURN part_name;
END $$;

-- 建 2026-10 ~ 2027-03 六个月（按需改范围）
SELECT ensure_flight_log_partition(d::date)
FROM generate_series('2026-10-01'::date, '2027-03-01'::date, INTERVAL '1 month') AS d;

-- ===== 3. 每个分区上的查询索引 =====
-- 索引建在父表上会自动下推到每个分区（含之后新建的分区）。
-- 只保留三个：任务回放、按机查询、去重。
CREATE INDEX IF NOT EXISTS idx_flight_log_tenant_task_time
    ON flight_log_p (tenant_id, task_id, timestamp);
CREATE INDEX IF NOT EXISTS idx_flight_log_sysid_time
    ON flight_log_p (sysid, timestamp);
CREATE UNIQUE INDEX IF NOT EXISTS uq_flight_log_tenant_sysid_seq
    ON flight_log_p (tenant_id, sysid, seq);

